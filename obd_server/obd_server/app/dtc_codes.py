def describe_unknown(code: str) -> tuple[str, str]:
    """Загальний опис для коду, якого немає в словнику."""
    area_uk, area_en = _AREA.get(code[0], ("", ""))
    generic = code[1] == "0"
    note_uk = "узагальнений код" if generic else "код виробника, точне значення дивись у документації марки"
    note_en = "generic code" if generic else "manufacturer-specific code, see the make's documentation"
    group_uk = group_en = ""
    if code[0] == "P" and code[2] in _GROUPS_P:
        group_uk, group_en = _GROUPS_P[code[2]]
        group_uk, group_en = f", {group_uk}", f", {group_en}"
    return (f"{area_uk}{group_uk} ({note_uk})", f"{area_en}{group_en} ({note_en})")
